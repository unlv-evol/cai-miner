#!/usr/bin/env python3
"""Build the GHAgentCI website (GitHub Pages) from the released tables.

    python3 scripts/build_site.py RELEASE -o _site
    python3 -m http.server -d _site 8000                 # then open localhost:8000

RELEASE is a directory holding the four released tables, gzipped as on Zenodo
(repositories, revisions, steps and ghaw_manifests ``.csv.gz``) or not. The
site is the landing page (site/index.html) with the explorer under
``explorer/``. Built from the public release, the explorer's data is identical
to a build from the raw mining output, apart from the count of repositories
whose only evidence is the generic_ai group, which the release leaves out.
"""

from __future__ import annotations

import argparse
import gzip
import shutil
import sys
import tempfile
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_explorer

ROOT = Path(__file__).resolve().parents[1]
TABLES = ("repositories", "revisions", "steps", "ghaw_manifests")
# The days GHAgentCI was mined (RUN.txt of the full run).
COLLECTED = ("2026-10-03", "2026-10-05")

HOME_LINK_CSS = (
    "<style>.brand h1 a.home { color: inherit; text-decoration: none; }"
    " .brand h1 a.home:hover { color: var(--accent); }</style>\n"
)


def unpack(release: Path, into: Path) -> None:
    """The tables as plain CSV, which the explorer build reads."""
    for name in TABLES:
        plain, packed = release / f"{name}.csv", release / f"{name}.csv.gz"
        if plain.exists():
            shutil.copyfile(plain, into / plain.name)
        elif packed.exists():
            with gzip.open(packed, "rb") as source, (into / plain.name).open("wb") as target:
                shutil.copyfileobj(source, target)
        else:
            raise SystemExit(f"{release}: no {name}.csv or {name}.csv.gz")


def explorer_page(app: str) -> str:
    """The explorer as a page of the site: a document around the app, with its
    title linking back to the landing page."""
    title = "<h1>GHAgentCI <span>Explorer</span></h1>"
    if app.count(title) != 1:
        raise SystemExit("explorer/app.html: header title not found; update build_site.py")
    app = app.replace(
        title, '<h1><a class="home" href="../">GHAgentCI</a> <span>Explorer</span></h1>'
    )
    icon = (ROOT / "site" / "index.html").read_text(encoding="utf-8")
    icon = next(line for line in icon.splitlines() if 'rel="icon"' in line)
    return (
        '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
        f"{icon.strip()}\n{HOME_LINK_CSS}"
        "<!-- Generated by scripts/build_site.py from explorer/app.html. -->\n"
        "</head>\n<body>\n" + app + "\n</body>\n</html>\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("release", help="directory with the released tables")
    parser.add_argument("-o", "--out", default=str(ROOT / "_site"), help="site directory")
    args = parser.parse_args(argv)
    release, site = Path(args.release), Path(args.out)

    if site.exists():
        shutil.rmtree(site)
    (site / "explorer").mkdir(parents=True)
    shutil.copyfile(ROOT / "site" / "index.html", site / "index.html")
    (site / ".nojekyll").write_text("")  # serve files as they are

    with tempfile.TemporaryDirectory() as tmp:
        unpack(release, Path(tmp))
        first, last = (date.fromisoformat(d) for d in COLLECTED)
        build_explorer.main(
            [tmp, "-o", str(site / "explorer"), "--collected", first.isoformat(), last.isoformat()]
        )

    app = (ROOT / "explorer" / "app.html").read_text(encoding="utf-8")
    (site / "explorer" / "index.html").write_text(explorer_page(app), encoding="utf-8")
    print(f"site written to {site}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
